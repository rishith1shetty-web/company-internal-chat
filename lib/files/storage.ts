/**
 * File storage on the company server's own filesystem (CLAUDE.md §11, Phase 7).
 *
 * The only module that touches the storage directory. Everything above it works with an opaque
 * `storageKey`; nothing above it ever sees or constructs a filesystem path, which is what keeps
 * "where is this file" from becoming an input.
 *
 * THE RULES THIS FILE EXISTS TO ENFORCE:
 *
 * 1. **A stored path is never derived from anything a client sent.** Names are generated here
 *    from a UUID. The original filename is metadata in PostgreSQL and nothing else — it is never
 *    a path segment, never a directory, and never influences where bytes land. Two people
 *    uploading `report.pdf` therefore cannot collide, and neither can overwrite the other.
 *
 * 2. **Every resolved path is checked to be inside the root**, after resolution rather than
 *    before. Prefix-checking a string before `resolve()` is how `..` gets through; resolving
 *    first and then testing containment is what actually holds.
 *
 * 3. **Nothing incomplete ever appears in permanent storage.** Bytes are streamed to a temporary
 *    file and moved into place only once the whole body has arrived within the size limit. The
 *    move is a rename inside one filesystem, so a reader either sees a complete file or no file.
 *
 * 4. **Nothing here interprets the bytes.** No execution, no shelling out, no dynamic import, no
 *    extension-based behaviour. A stored file is a sequence of bytes with a name in a database
 *    row (CLAUDE.md §11, docs/04-security.md R-07).
 */

import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rename, rm, stat } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { pipeline } from 'node:stream/promises';
import type { Readable } from 'node:stream';

/** Where in-progress uploads live. Inside the root, so the move to permanent storage is a rename. */
const TEMP_DIRECTORY = 'tmp';

export type StorageFailure =
  | 'TOO_LARGE'
  | 'WRITE_FAILED'
  | 'NOT_FOUND'
  | 'OUTSIDE_ROOT';

export class StorageError extends Error {
  readonly reason: StorageFailure;

  constructor(reason: StorageFailure, message: string) {
    super(message);
    this.name = 'StorageError';
    this.reason = reason;
  }
}

export interface StorageConfig {
  /** Absolute path to the storage root, from `lib/config/env.ts`. */
  uploadDir: string;
  /** Ceiling in bytes, enforced while the body is still arriving. */
  maxFileSize: number;
}

export interface StoredFile {
  /** Relative, opaque, and the only handle anything above this module holds. */
  storageKey: string;
  /** Counted here as the bytes went past — never taken from a header. */
  byteSize: number;
  /** SHA-256 of the stored bytes, computed in the same pass. */
  checksumSha256: string;
}

/**
 * Generates the relative storage key for a new upload.
 *
 * Date-sharded so a directory holding years of company files stays a reasonable size, and named
 * from a UUID so it carries nothing about the sender, the conversation or the original filename.
 * The `.bin` suffix is deliberate and uniform: the stored file has no meaningful extension,
 * which removes any chance of the filesystem, a backup tool or a misconfigured web server
 * treating it as executable or serving it by type.
 */
export function generateStorageKey(now: Date = new Date()): string {
  const year = String(now.getUTCFullYear());
  const month = String(now.getUTCMonth() + 1).padStart(2, '0');
  return `${year}/${month}/${randomUUID()}.bin`;
}

/**
 * Resolves a storage key to an absolute path, and refuses anything that escapes the root.
 *
 * Keys are generated by this module, so in normal operation nothing here can fail. It is written
 * as a check anyway: this is the single point where a key becomes a filesystem path, and the day
 * a key reaches it from somewhere less careful — a database row edited by hand, a future import
 * tool — this is the only thing standing between that and an arbitrary file read.
 */
export function resolveStoragePath(config: StorageConfig, storageKey: string): string {
  const root = resolve(config.uploadDir);
  const target = resolve(root, storageKey);

  if (target !== root && !target.startsWith(root + sep)) {
    throw new StorageError(
      'OUTSIDE_ROOT',
      'That file is not inside the storage directory.',
    );
  }

  return target;
}

/** Creates the storage root and its temporary directory if they do not exist yet. */
export async function ensureStorageReady(config: StorageConfig): Promise<void> {
  await mkdir(join(resolve(config.uploadDir), TEMP_DIRECTORY), { recursive: true });
}

/**
 * Streams an upload to permanent storage, returning what was actually written.
 *
 * The body is never held in memory: it is piped through a hash and a byte counter straight to a
 * temporary file, so a 500 MB video costs a buffer's worth of RAM rather than 500 MB of it.
 *
 * The size limit is enforced **during** the transfer. Waiting until the end to measure would
 * mean writing the whole of an oversized upload to disk before rejecting it, which is a way to
 * fill a disk with a request that was always going to fail.
 *
 * On any failure — oversize, a broken connection, a full disk — the temporary file is removed and
 * nothing is left in permanent storage. The caller gets an error and has no row to clean up,
 * because the database has not been touched yet.
 */
export async function storeStream(
  config: StorageConfig,
  storageKey: string,
  body: Readable,
): Promise<StoredFile> {
  const finalPath = resolveStoragePath(config, storageKey);
  const tempPath = join(
    resolve(config.uploadDir),
    TEMP_DIRECTORY,
    `${randomUUID()}.part`,
  );

  await mkdir(dirname(tempPath), { recursive: true });
  await mkdir(dirname(finalPath), { recursive: true });

  const hash = createHash('sha256');
  let byteSize = 0;
  let tooLarge = false;

  try {
    await pipeline(
      body,
      async function* count(source: AsyncIterable<Buffer>) {
        for await (const chunk of source) {
          byteSize += chunk.length;

          if (byteSize > config.maxFileSize) {
            /*
             * Stop at the moment the limit is passed. Throwing here tears down the pipeline,
             * which destroys the source stream and stops the client sending the rest — the
             * request does not have to be read to completion to be refused.
             */
            tooLarge = true;
            throw new StorageError('TOO_LARGE', 'That file is larger than the limit.');
          }

          hash.update(chunk);
          yield chunk;
        }
      },
      createWriteStream(tempPath),
    );
  } catch (error) {
    // Best-effort: the upload has already failed, and a missing temporary file is not a problem.
    await rm(tempPath, { force: true }).catch(() => {});

    if (tooLarge || (error instanceof StorageError && error.reason === 'TOO_LARGE')) {
      throw new StorageError('TOO_LARGE', 'That file is larger than the limit.');
    }

    throw new StorageError('WRITE_FAILED', 'The file could not be saved.');
  }

  try {
    /*
     * Atomic within one filesystem, which is why the temporary directory lives inside the
     * storage root rather than in the system temp directory. A reader sees either no file or the
     * complete file — never a half-written one.
     */
    await rename(tempPath, finalPath);
  } catch {
    await rm(tempPath, { force: true }).catch(() => {});
    throw new StorageError('WRITE_FAILED', 'The file could not be saved.');
  }

  return { storageKey, byteSize, checksumSha256: hash.digest('hex') };
}

/**
 * Removes a stored file. Used to roll back when the database write fails after the bytes landed.
 *
 * Never throws: it is called on a path where something has already gone wrong, and a failure to
 * tidy up must not replace the error the caller is actually reporting. A file left behind is
 * inert — nothing can reach it without a database row naming it.
 */
export async function deleteStoredFile(
  config: StorageConfig,
  storageKey: string,
): Promise<boolean> {
  try {
    await rm(resolveStoragePath(config, storageKey), { force: true });
    return true;
  } catch {
    return false;
  }
}

/** The size of a stored file, or null when it is not there. */
export async function statStoredFile(
  config: StorageConfig,
  storageKey: string,
): Promise<{ byteSize: number } | null> {
  try {
    const stats = await stat(resolveStoragePath(config, storageKey));
    return stats.isFile() ? { byteSize: stats.size } : null;
  } catch {
    return null;
  }
}

/**
 * Opens a stored file for reading.
 *
 * Returns a stream rather than a buffer for the same reason uploads are streamed: a download of a
 * large file must not be read into the server's memory first.
 */
export function openStoredFile(config: StorageConfig, storageKey: string): Readable {
  return createReadStream(resolveStoragePath(config, storageKey));
}
