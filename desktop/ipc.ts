/**
 * The contract between the main process and the preload script.
 *
 * A SEPARATE MODULE FOR A CONCRETE REASON, not tidiness. The channel names have to be identical
 * on both sides or a message is silently sent into nothing, so they must be shared — but the
 * preload script calls `contextBridge.exposeInMainWorld` at module scope, and `contextBridge`
 * does not exist in the main process. Importing the names from preload.ts therefore *runs* that
 * call in the main process and crashes Electron on startup, which is exactly what it did before
 * this file existed.
 *
 * So: names and types here, where both sides can import them and neither side executes anything.
 */

/** IPC channel names. Prefixed so they are distinguishable in a trace. */
export const CHANNELS = {
  /** Renderer → main: show a native Windows notification. */
  notify: 'desktop:notify',
  /** Renderer → main: dismiss one previously shown. */
  closeNotification: 'desktop:notification-close',
  /** Main → renderer: the employee clicked a notification. Carries its id. */
  notificationClicked: 'desktop:notification-clicked',
  /** Renderer → main: load the company server again. Used by the offline screen's retry. */
  reload: 'desktop:reload',
  /** Renderer → main, with a reply: what the offline screen needs to explain itself. */
  connectionInfo: 'desktop:connection-info',
} as const;

/** What the page sends when it wants a Windows notification. Re-validated in the main process. */
export interface DesktopNotifyPayload {
  /** Generated by the page so a click can be routed back to the right popup. */
  id: string;
  title: string;
  body: string;
  tag: string;
  silent: boolean;
}

export interface DesktopConnectionInfo {
  serverUrl: string;
  /** True for http: to anything but loopback, so the interface can say so if it wants to. */
  insecure: boolean;
  /** A short, non-technical description of the last failure. Never a stack or a path. */
  message: string;
}
